--[[
  custom_scripts/screenplays/population/street_lines.lua

  Ambient overheard dialogue for the population screenplay. PURE DATA:
  no functions, no require/includeFile, no side effects. Must load under
  plain lua5.3 with no engine stubs (same rule as warreport/war_contrib.lua,
  which deploy/tests/assert-contrib-flush.sh loads that way).

  Contract with the consumer:
    - exactly four pools: plaza_quiet, plaza_frontier, plaza_contested, cantina
    - the consumer refuses to speak for any pool under 60 lines; every pool
      here carries at least 70 so review cuts cannot trip that floor
    - every line is unique across the whole file
    - plain ASCII literal strings, never an at-sign key (no client string tables ship)
    - faction-neutral: a town can flip, so no line names either side as
      good or bad or assumes which side the listener is on
    - nothing promises a quest, names a mechanic, or tells the player to act

  Pool meanings (chosen by the consumer from the town's live war state):
    plaza_quiet      far from the fighting, supply connected, ordinary life
    plaza_frontier   border town, war real but elsewhere, rumour and unease
    plaza_contested  fighting in or near the town now; civilians have fled,
                     these are the ones who stayed or could not leave
    cantina          indoors, drinking, looser and funnier
]]

